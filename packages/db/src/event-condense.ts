export function condenseEventTypes(db: Database.Database, workspaceId?: string): { renamed: number; deleted: number } {
  db.exec("CREATE TEMP TABLE IF NOT EXISTS event_condense (old TEXT PRIMARY KEY, new TEXT NOT NULL, a TEXT NOT NULL, b TEXT NOT NULL)");
  db.exec("DELETE FROM temp.event_condense");
  const insert = db.prepare("INSERT INTO temp.event_condense (old, new, a, b) VALUES (?, ?, ?, ?)");
  for (const [old, type, value] of CONDENSED_EVENT_TYPES) {
    const [a, b = ""] = value.split("|");
    insert.run(old, type, a, b);
  }
  const scope = workspaceId === undefined ? "" : " AND events.workspace_id = ?";
  const params = workspaceId === undefined ? [] : [workspaceId];
  // Every payload is made an object first; a scalar or array payload is kept under `payload`.
  const object = `CASE WHEN json_valid(events.payload_json) AND json_type(events.payload_json) = 'object' THEN events.payload_json
    WHEN json_valid(events.payload_json) THEN json_object('payload', json(events.payload_json)) ELSE json_object('payload', events.payload_json) END`;
  const renamed = db.prepare(`
    UPDATE events SET type = m.new, payload_json = CASE
      WHEN m.new = 'person.decided' THEN json_set(json_insert(${object}, '$.decision', m.b), '$.subject', m.a)
      WHEN m.new = 'job.ran' THEN json_set(CASE WHEN json_type(${object}, '$.state') IS NULL THEN ${object}
          ELSE json_set(json_remove(${object}, '$.state'), '$.result', json(${object} -> '$.state')) END, '$.job', m.a, '$.state', m.b)
      WHEN m.old = m.new THEN json_insert(${object}, '$.change', m.a)
      -- A payload that already carried its own change (none found locally; the hosted ledger was not inspected) keeps it as priorChange.
      WHEN json_type(${object}, '$.change') IS NOT NULL THEN json_set(json_set(${object}, '$.priorChange', json(${object} -> '$.change')), '$.change', m.a)
      ELSE json_set(${object}, '$.change', m.a) END
    FROM temp.event_condense m
    WHERE events.type = m.old AND (m.old <> m.new OR CASE WHEN json_valid(events.payload_json) THEN json_type(events.payload_json, '$.change') END IS NULL)${scope}`).run(...params).changes;
  const deleted = db.prepare(`DELETE FROM events WHERE type IN (${CONDENSED_TICK_TYPES.map(() => "?").join(", ")})${workspaceId === undefined ? "" : " AND workspace_id = ?"}`)
    .run(...CONDENSED_TICK_TYPES, ...params).changes;
  db.exec("DELETE FROM temp.event_condense");
  return { renamed, deleted };
}
