import { expect, test, vi } from "vitest";

vi.mock("server-only", () => ({}));
const TEST_CTX = { principalId: "p1", workspaceId: "w1", role: "owner" as const,
  identity: { provider: "credential" as const, issuer: "test", subject: "p1" },
  authMethod: "session" as const, requestId: "test-request" };
vi.mock("../../../../lib/access-guard", () => ({ resolveAccessContext: async () => ({ ctx: TEST_CTX }) }));

const issueDeviceLease = vi.fn();
vi.mock("../../../../lib/crossline", () => ({ getStore: () => ({ issueDeviceLease: (...args: unknown[]) => issueDeviceLease(...args) }) }));

const post = async (body: unknown) => {
  const { POST } = await import("./route");
  return POST(new Request("http://local/api/auth/device-lease", {
    method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(body)
  }));
};

test("issues a 24-hour lease bound to the caller's own principal and workspace", async () => {
  issueDeviceLease.mockImplementationOnce((lease) => lease);
  const response = await post({ deviceId: "device-1" });
  expect(response.status).toBe(200);
  const body = await response.json() as { ok: boolean; deviceId: string; expiresAt: string };
  expect(body.ok).toBe(true);
  expect(body.deviceId).toBe("device-1");
  expect(issueDeviceLease).toHaveBeenCalledTimes(1);
  const [lease] = issueDeviceLease.mock.calls[0]!;
  expect(lease).toMatchObject({ principalId: "p1", workspaceId: "w1", deviceId: "device-1" });
  expect(Date.parse(body.expiresAt) - Date.parse(lease.issuedAt)).toBe(24 * 60 * 60_000);
});

test("rejects a device id that could not have been generated by this app", async () => {
  const response = await post({ deviceId: "../not-a-uuid" });
  expect(response.status).toBe(400);
  await expect(response.json()).resolves.toEqual({ ok: false, code: "DEVICE_ID_INVALID" });
  expect(issueDeviceLease).not.toHaveBeenCalled();
});

test("a forged cross-site Origin is refused before touching the store", async () => {
  const { POST } = await import("./route");
  const response = await POST(new Request("http://local/api/auth/device-lease", {
    method: "POST", headers: { "content-type": "application/json", origin: "https://evil.example" },
    body: JSON.stringify({ deviceId: "device-1" })
  }));
  expect(response.status).toBe(403);
  expect(issueDeviceLease).not.toHaveBeenCalled();
});
